# Typographic dashes land on the hyphen glyph.
_ALIASES = {'−': '-', '—': '-', '–': '-'}

BLANK = _G[' ']


def glyph_for(ch):
    """The 7x5 glyph rows for a character, or None when the dot
    font cannot draw it (kana/kanji — the caller falls back to the
    system font for those runs)."""
    return _G.get(_ALIASES.get(ch, ch))


def is_dot_char(ch):
    return glyph_for(ch) is not None


def segments(text):
    """Split a string into (run, is_dot) pieces: maximal runs of
    dot-renderable characters and of font-fallback characters, so a
    mixed readout like '残り 36:12' draws its digits as dots and its
    kanji in the system font."""
    out = []
    for ch in text:
        dot = is_dot_char(ch)
        if out and out[-1][1] == dot:
            out[-1] = (out[-1][0] + ch, dot)
        else:
            out.append((ch, dot))
    return out


def text_units(text):
    """Width of a pure dot string in dot units, tracking included
    (no trailing tracking after the last character)."""
    if not text:
        return 0
    return len(text) * ADVANCE - 1


def text_width_px(text, pitch):
    """Pixel width of a pure dot string at a given dot pitch."""
    return text_units(text) * pitch
